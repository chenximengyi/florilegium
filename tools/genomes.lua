-- Write the species genome tables for the browser demo, and a reference the demo's
-- JavaScript is checked against. The tables are taken from florilegium-species.lua
-- itself, so the browser samples the same genome the PDF does and not a copy of it.
--   lua tools/genomes.lua                   write demo/fullscreen/species-data.js
--   lua tools/genomes.lua --check [D]       print D documents' pools, every trait, as
--                                           the demo's species.js computes them
package.path = "./?.lua;" .. package.path
local species = require("florilegium-species")
local pm = require("florilegium-pgfmath")
local fmt = string.format

-- as the locals in florilegium-species.lua (M.pool, M.showy): the eight slots of a
-- document and the clusters the margin paints sparingly, so both heroes are showy
local SLOTS = { "hero", "hero", "spray", "spray", "monocot", "any", "any", "any" }
local SPRAYS = { cumbel = true, raceme = true, spike = true, panicle = true, thyrse = true,
  catkin = true, monochasium = true }

-- a real trait as an integer number of 65536ths, so that the reference and the
-- JavaScript compare exactly; a string or a whole number as itself
local function values(sp)
  local t = {}
  for _, k in ipairs(species.TRAITS) do
    local v = sp[k]
    if math.type(v) == "float" then
      t[#t + 1] = fmt("%s=%dsp", k, math.floor(v * 65536 + 0.5))
    else
      t[#t + 1] = fmt("%s=%s", k, tostring(v))
    end
  end
  return table.concat(t, " ")
end

if arg[1] == "--check" then
  local docs = tonumber(arg[2]) or 4
  for d = 0, docs - 1 do
    local pool = species.pool(d)
    for i, sp in ipairs(pool) do
      print(fmt("pool %d %d %d %s", d, i, sp.seed, values(sp)))
    end
  end
  return
end

-- a distribution as JavaScript reads it: R(a, b) as the two integers pgfmath's
-- \flo@R{a}{b-a} would hold, so the browser does no decimal arithmetic of its own
local function conv(v)
  if type(v) ~= "table" then return v end
  if v[1] == "r" then
    return { "r", pm.sp(tostring(v[2])), pm.sp(tostring(v[3] - v[2])) }
  end
  local out = {}
  for k, x in pairs(v) do out[k] = conv(x) end
  return out
end

local function esc(s)
  return '"' .. tostring(s):gsub('[%z\1-\31\\"]', function(c)
    if c == '"' then return '\\"' elseif c == "\\" then return "\\\\" end
    return fmt("\\u%04x", c:byte())
  end) .. '"'
end

local function enc(v)
  local t = type(v)
  if t == "string" then return esc(v) end
  if t == "number" then
    if math.type(v) == "integer" then return fmt("%d", v) end
    if v == math.floor(v) then return fmt("%d", v) end
    return fmt("%.17g", v)
  end
  if t == "boolean" then return tostring(v) end
  assert(t == "table", "cannot encode a " .. t)
  if #v > 0 then
    local parts = {}
    for i = 1, #v do parts[i] = enc(v[i]) end
    return "[" .. table.concat(parts, ",") .. "]"
  end
  local keys = {}
  for k in pairs(v) do keys[#keys + 1] = tostring(k) end
  table.sort(keys)
  local parts = {}
  for _, k in ipairs(keys) do
    local x = v[k]
    if x == nil then x = v[tonumber(k)] end
    parts[#parts + 1] = esc(k) .. ":" .. enc(x)
  end
  return "{" .. table.concat(parts, ",") .. "}"
end

-- every trait's distribution for every plan, resolved here (M.dist: the plan's own, else
-- its clade's, else everyone's), so the browser needs no botany of its own
local doc = { version = species.version, warm = species.WARM, traits = species.TRAITS,
  slots = SLOTS, roles = species.ROLES, sprays = SPRAYS, plans = {} }
for _, p in ipairs(species.PLANS) do
  local d = {}
  for i = 2, #species.TRAITS do
    local t = species.TRAITS[i]
    d[t] = conv(species.dist(p.name, t))
  end
  doc.plans[#doc.plans + 1] = {
    name = p.name, clade = p.clade, w = p.w,
    roles = p.roles or {}, apart = p.apart and true or false, dist = d,
  }
end

local f = assert(io.open("demo/fullscreen/species-data.js", "w"))
f:write("// Generated by tools/genomes.lua from florilegium-species.lua: do not edit.\n")
f:write("// The species genome tables, resolved, as the browser demo samples them.\n")
f:write("globalThis.FLORILEGIUM_SPECIES = " .. enc(doc) .. ";\n")
f:close()
print(fmt("demo/fullscreen/species-data.js: %d plans, %d traits, version %s",
  #doc.plans, #doc.traits, doc.version))
